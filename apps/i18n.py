def ui_strings(locale: str) -> dict:
    """Return the UI strings for `locale`, falling back to English per key.

    Raises ImproperlyConfigured for an unsupported locale (fail-closed: the
    organization model validates preferred_locale against LOCALES, so a
    non-supported value reaching here is a programming error, not user input).
    """
    if locale not in LOCALES:
        raise ImproperlyConfigured(
            "UI locale {} is not a supported interface language.".format(locale)
        )
    strings = dict(UI_STRINGS["en"])
    strings.update(UI_STRINGS[locale])
    return strings


def translate(key: str, locale: str) -> str:
    """Single label lookup, for view code that builds navigation data."""
    if locale not in UI_STRINGS:
        raise LookupError("No UI glossary for locale {}.".format(locale))
    try:
        return UI_STRINGS[locale][key]
    except KeyError:
        return UI_STRINGS["en"][key]
