"""Central UI string glossary - the terminology source for every locale (SRS 8.3).

ORG-004/ORG-005: the product interface speaks en, fr and ar, and Arabic screens
use a genuine RTL layout rather than translated-only LTR text.

Views call ui_strings(organization.preferred_locale) and pass the result to the
template context; templates and static pages contain no literal product copy, so
one glossary drives every screen. Arabic screens also receive ui.code == "ar"
plus ui.dir == "rtl", which the base template maps to <html dir> and which the
stylesheet uses through logical (direction-relative) CSS properties.

Compiled gettext catalogs are deliberately NOT used here: the gettext tooling
(msgfmt/xgettext) is absent from the development host, so a shipped glossary is
the mechanism that can be verified by tests (docs/DECISIONS.md D19). If
gettext catalogs are introduced later they must extend, not duplicate, these
keys.

Status of the other columns (audited by script against the dicts below, not by
eye; each figure counts one column's own keys, and a caller receives the
English keys merged under the chosen column):
- English carries 897 keys: the 478 of the phase 3D cut, the 65 new keys
  the phase 3E rooms, schedules and cancellation copy added, the 208 the
  phase 3F finance slice added, the 35 row labels the finance pages' own
  templates added at the same time, the 110 the phase 3G grading
  slice added, and the 1 the security hardening pass added.
- "fr" is NOT translated yet. It names 75 of the 897 English keys, and those
  75 are only the base rows: the other 822 keys are absent there and fall back
  to English.
  Two of those
  75 differ from English ("code" = "fr" and a partly-French tagline); the other
  73 are byte-identical to the English source. A center set to fr therefore
  displays English copy. Filling that column is the i18n feature, not this
  slice; see docs/OPEN_QUESTIONS.md.
- "ar" names 135 of the 897 keys: the same 75 base rows plus the 60 the students
  feature added. The other 762 keys are not named there at all and fall back
  to English.
  None of the 135 is real Arabic wording: 130 of them are machine transliterated
  with Latin letters, four (the tagline and the three sign rows) mix one or two
  Arabic letters into that transliteration, and only the proper noun app_name is
  shared with English. None of it
  is reviewed by a native Arabic speaker, and some distinct English ideas
  currently share one transliteration (the ar rows for field_student_number and
  field_status are identical, as are field_note and status_applicant), so those
  rows cannot be told apart on screen. An Arabic screen therefore shows a
  transliteration, not real Arabic wording. Rewriting that column in Arabic
  script, and checking every row, needs a native speaker; the product's language
  setting is a display switch (ORG-002) whose wording is still unverified. See
  docs/OPEN_QUESTIONS.md.
"""

